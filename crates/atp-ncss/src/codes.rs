/// The name of an industry's code (`000304`), as the company pages show it.
pub fn industry_name(code: &str) -> Option<&'static str> {
  INDUSTRIES
    .iter()
    .chain(INDUSTRY_GROUPS)
    .find(|(c, _)| *c == code)
    .map(|(_, name)| *name)
}
